"""Generate the psychnanovg binding from nanovg.h.

Run with `uv run gen/generate.py` from the project root, or `build.m gen`.

The generator reads `third_party/nanovg/src/nanovg.h`, applies the exclusions
and renames in `gen/allowlist.txt`, and writes:

    src/gen_dispatch.c      sorted command table and one handler per function
    src/gen_enums.c         sorted NVG_* name to value table
    m/PsychNanoVG.m         help text and the command list
    m/PsychNanoVGOp.m       opcode constants
    tests/test_gen_marshal.m  one call per generated subcommand

Generation exists so that the help text, the argument checks, and the
marshaling tests all come from the same description of each function. A
signature that no rule in SPEC 7.2 covers is dropped and reported, rather
than bound with a guess.
"""

