def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def wrap_c_string(s, width=64):
    """Split a long help string into adjacent C string literals."""
    words, lines, cur = s.split(), [], ""
    for w in words:
        if cur and len(cur) + 1 + len(w) > width:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + " " + w).strip()
    if cur:
        lines.append(cur)
    if not lines:
        return '""'
    return "\n        ".join(c_string(ln + (" " if i + 1 < len(lines) else ""))
                             for i, ln in enumerate(lines))


def emit_handler(b):
    """C source of one generated handler."""
    L = []
    L.append("static void h_%s(int nlhs, mxArray *plhs[], int nrhs,"
             " const mxArray *prhs[])" % b.mname)
    L.append("{")
    body = []
    call_args = []
    argi = 0
    str_var = None
    decls = []
    post = []
    outs = b.outputs
    has_out = len(outs) > 0

    for p in b.params:
        k = p.kind
        if k == "CTX":
            call_args.append("PNVG_VG")
        elif k == "F":
            decls.append("    float %s;" % p.name)
            body.append('    %s = pnvg_arg_float(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "I":
            decls.append("    int %s;" % p.name)
            body.append('    %s = pnvg_arg_int(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "UC":
            decls.append("    unsigned char %s;" % p.name)
            body.append('    %s = pnvg_arg_uchar(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "ENUM":
            decls.append("    int %s;" % p.name)
            body.append('    %s = pnvg_arg_enum(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "IMAGE":
            decls.append("    int %s;" % p.name)
            body.append('    %s = pnvg_arg_image(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "FONT":
            decls.append("    int %s;" % p.name)
            body.append('    %s = pnvg_arg_font(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "COLOR":
            decls.append("    NVGcolor %s;" % p.name)
            body.append('    %s = pnvg_arg_color(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "PAINT":
            decls.append("    NVGpaint %s;" % p.name)
            body.append('    %s = pnvg_arg_paint(prhs[%d], %d, "%s");'
                        % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k == "STR":
            var = "s_" + p.name
            decls.append("    pnvg_str %s;" % var)
            body.append('    pnvg_arg_string(prhs[%d], %d, "%s", &%s);'
                        % (argi, argi, b.mname, var))
            post.append("    pnvg_str_free(&%s);" % var)
            call_args.append("%s.p" % var)
            str_var = var
            argi += 1
        elif k == "STREND":
            call_args.append("%s.p + %s.n" % (str_var, str_var))
        elif k == "XFORM_IN":
            decls.append("    float %s[6];" % p.name)
            body.append('    pnvg_arg_xform(prhs[%d], %d, "%s", %s);'
                        % (argi, argi, b.mname, p.name))
            call_args.append(p.name)
            argi += 1
        elif k == "XFORM_INOUT":
            decls.append("    float %s[6];" % p.name)
            body.append('    pnvg_arg_xform(prhs[%d], %d, "%s", %s);'
                        % (argi, argi, b.mname, p.name))
            call_args.append(p.name)
            argi += 1
        elif k == "XFORM_OUT":
            decls.append("    float %s[6] = {1,0,0,1,0,0};" % p.name)
            call_args.append(p.name)
        elif k == "BOUNDS_OUT":
            decls.append("    float %s[4] = {0,0,0,0};" % p.name)
            call_args.append(p.name)
        elif k == "FOUT":
            decls.append("    float %s = 0.0f;" % p.name)
            call_args.append("&" + p.name)
        elif k == "IOUT":
            decls.append("    int %s = 0;" % p.name)
            call_args.append("&" + p.name)
        elif k == "DATA":
            decls.append("    const unsigned char *%s;" % p.name)
            decls.append("    int n_%s;" % p.name)
            body.append('    %s = pnvg_arg_bytes(prhs[%d], %d, "%s", &n_%s);'
                        % (p.name, argi, argi, b.mname, p.name))
            call_args.append("(unsigned char *)" + p.name)
            argi += 1
        elif k == "NDATA":
            call_args.append("n_data")
        elif k == "FREEDATA":
            # SPEC 7.3: the MEX always copies and never lets NanoVG free the
            # caller's buffer.
            call_args.append("0")
        elif k == "IMGDATA":
            decls.append("    const unsigned char *%s;" % p.name)
            decls.append("    int imgw = 0, imgh = 0;")
            body.append('    %s = pnvg_arg_image_data(prhs[%d], %d, "%s",'
                        " &imgw, &imgh);" % (p.name, argi, argi, b.mname))
            call_args.append(p.name)
            argi += 1
        elif k in ("IMGW", "IMGH"):
            call_args.append("imgw" if k == "IMGW" else "imgh")
        elif k == "GLYPHS_OUT":
            call_args.append("pos_buf")
        elif k == "MAXGLYPHS":
            call_args.append("max_positions")
        elif k == "ROWS_OUT":
            call_args.append("row_buf")
        elif k == "MAXROWS":
            body.append("    max_rows = (nrhs > %d) ?"
                        ' pnvg_arg_int(prhs[%d], %d, "%s") : 64;'
                        % (argi, argi, argi, b.mname))
            body.append('    if (max_rows < 1 || max_rows > PNVG_MAX_ROWS)')
            body.append('        pnvg_err("psychnanovg:Range", "%s: maxRows'
                        ' must be 1 to %%d", PNVG_MAX_ROWS);' % b.mname)
            call_args.append("max_rows")
            argi += 1
        else:
            raise Unsupported("no emitter for kind %s" % k)

    if any(p.kind == "GLYPHS_OUT" for p in b.params):
        decls.append("    NVGglyphPosition pos_buf[PNVG_MAX_GLYPHS];")
        decls.append("    int max_positions;")
        body.append("    max_positions = (int)s_string.n;")
        body.append("    if (max_positions > PNVG_MAX_GLYPHS)"
                    " max_positions = PNVG_MAX_GLYPHS;")
    if any(p.kind == "ROWS_OUT" for p in b.params):
        decls.append("    NVGtextRow row_buf[PNVG_MAX_ROWS];")
        decls.append("    int max_rows;")

    ret_decl = ""
    if b.ret == "float":
        ret_decl = "    float ret;"
        call = "    ret = %s(%s);" % (b.cname, ", ".join(call_args))
    elif b.ret == "int":
        ret_decl = "    int ret;"
        call = "    ret = %s(%s);" % (b.cname, ", ".join(call_args))
    elif b.ret == "NVGcolor":
        ret_decl = "    NVGcolor ret;"
        call = "    ret = %s(%s);" % (b.cname, ", ".join(call_args))
    elif b.ret == "NVGpaint":
        ret_decl = "    NVGpaint ret;"
        call = "    ret = %s(%s);" % (b.cname, ", ".join(call_args))
    else:
        call = "    %s(%s);" % (b.cname, ", ".join(call_args))
    if ret_decl:
        decls.append(ret_decl)

    L.extend(decls)
    L.append("    (void)nlhs; (void)nrhs; (void)plhs; (void)prhs;")
    L.extend(body)
    L.append(call)

    # Outputs. The string buffers are freed after the outputs are built,
    # because the glyph and row outputs report byte offsets into them.
    slot = 0
    for label, kind in outs:
        guard = "    " if slot == 0 else "    if (nlhs > %d) " % slot
        if kind == "RET_NUM":
            L.append(guard + "plhs[%d] = mxCreateDoubleScalar((double)ret);" % slot)
        elif kind == "RET_COLOR":
            L.append(guard + "plhs[%d] = pnvg_make_color(ret);" % slot)
        elif kind == "RET_PAINT":
            L.append(guard + "plhs[%d] = mxCreateDoubleScalar("
                     "(double)pnvg_paint_store(&ret));" % slot)
        elif kind == "OUT_XFORM":
            L.append(guard + "plhs[%d] = pnvg_make_row(%s, 6);" % (slot, label))
        elif kind == "OUT_BOUNDS":
            L.append(guard + "plhs[%d] = pnvg_make_row(%s, 4);" % (slot, label))
        elif kind == "OUT_SCALAR":
            L.append(guard + "plhs[%d] = mxCreateDoubleScalar((double)%s);"
                     % (slot, label))
        elif kind == "OUT_PAIR":
            names = [p.name for p in b.params if p.kind in ("FOUT", "IOUT")]
            L.append(guard + "{")
            L.append("        float pair_[2];")
            L.append("        pair_[0] = (float)%s; pair_[1] = (float)%s;"
                     % (names[0], names[1]))
            L.append("        plhs[%d] = pnvg_make_row(pair_, 2);" % slot)
            L.append("    }")
        elif kind == "OUT_GLYPHS":
            L.append(guard + "plhs[%d] = pnvg_make_glyphs(pos_buf, ret,"
                     " s_string.p);" % slot)
        elif kind == "OUT_ROWS":
            L.append(guard + "plhs[%d] = pnvg_make_rows(row_buf, ret,"
                     " s_string.p);" % slot)
        slot += 1
    L.extend(post)
    L.append("}")
    return "\n".join(L)


def emit_dispatch(bindings, path, version):
    cmds = []
    for b in bindings:
        nmin = len(b.inputs)
        nmax = nmin + len(b.optional)
        nout = len(b.outputs)
        cmds.append((b.mname, "h_" + b.mname, nmin, nmax, nout, flags_for(b),
                     b.group, b.doc or (b.mname + ".")))
    for (name, fn, a, z, nout, flags, group, help_) in HANDWRITTEN:
        cmds.append((name, fn, a, z, nout, flags, group, help_))
    cmds.sort(key=lambda c: c[0])
    for i in range(1, len(cmds)):
        if cmds[i][0] == cmds[i - 1][0]:
            raise SystemExit(
                "two commands are both named %s. Exclude the generated one in "
                "gen/allowlist.txt or rename it." % cmds[i][0])

    L = ["/* %s */" % GENERATED_BY.replace("\n", "\n * "), ""]
    L.append('#include "pnvg_internal.h"')
    L.append("")
    L.append("/* Hand-written handlers, defined in psychnanovg.c,"
             " pnvg_batch.c, pnvg_targets.c. */")
    for (name, fn, _a, _z, _n, _f, _g, _h) in HANDWRITTEN:
        L.append("extern void %s(int, mxArray **, int, const mxArray **);" % fn)
    L.append("")
    for b in bindings:
        L.append(emit_handler(b))
        L.append("")
    L.append("const pnvg_cmd pnvg_cmds[] = {")
    for (name, fn, a, z, nout, flags, group, help_) in cmds:
        L.append("    { %s, %s, %d, %d, %d, %s, %s,\n        %s }," % (
            c_string(name), fn, a, z, nout, flags, c_string(group),
            wrap_c_string(help_)))
    L.append("};")
    L.append("const int pnvg_ncmds = %d;" % len(cmds))
    L.append('const char *const pnvg_version_string = %s;' % c_string(version))
    L.append("")
    write(path, "\n".join(L))
    return cmds


def emit_enums(values, path):
    names = sorted(values)
