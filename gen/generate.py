def flags_for(b):
    flags = []
    if b.cname in CREATE_IMAGE_FUNCS:
        flags.append("PNVG_F_MKIMG")
    if b.cname == "nvgDeleteImage":
        flags.append("PNVG_F_DELIMG")
    if b.cname in CREATE_FONT_FUNCS:
        flags.append("PNVG_F_MKFONT")
    if b.needs_ctx:
        flags.append("PNVG_F_INIT")
    if b.group in FRAME_GROUPS:
        flags.append("PNVG_F_FRAME")
    if b.group == "Text" and b.mname not in TEXT_NO_FRAME:
        flags.append("PNVG_F_FRAME")
    if b.group in GL_GROUPS or (b.group == "Text" and b.mname in TEXT_GL):
        flags.append("PNVG_F_GL")
    return "|".join(flags) if flags else "0"


