def type_name(decl):
    """Flatten a pycparser type into a string such as `const unsigned char *`."""
    if isinstance(decl, c_ast.PtrDecl):
        return (type_name(decl.type) + " *").strip()
    if isinstance(decl, c_ast.TypeDecl):
        quals = " ".join(decl.quals)
        inner = decl.type
        if isinstance(inner, c_ast.IdentifierType):
            base = " ".join(inner.names)
        elif isinstance(inner, (c_ast.Struct, c_ast.Union, c_ast.Enum)):
            base = inner.name or "?"
        else:
            base = "?"
        return (quals + " " + base).strip()
    raise Unsupported("odd declarator")


def classify(fn_name, params):
    """Turn C parameters into marshaling kinds, per SPEC 7.2."""
    out = []
    i = 0
    while i < len(params):
        p = params[i]
        name = p.name or ""
        t = type_name(p.type)
        nxt = params[i + 1] if i + 1 < len(params) else None
        nxt_t = type_name(nxt.type) if nxt is not None else ""
        nxt_name = (nxt.name or "") if nxt is not None else ""

        if t == "NVGcontext *":
            if i != 0:
                raise Unsupported("context is not the first parameter")
            out.append(Param("CTX", name, t))
        elif t == "NVGcolor":
            out.append(Param("COLOR", name, t))
        elif t == "NVGpaint":
            out.append(Param("PAINT", name, t))
        elif t == "float":
            out.append(Param("F", name, t))
        elif t in ("int", "const int"):
            if fn_name == "nvgCreateImageRGBA" and name in ("w", "h"):
                # SPEC 7.2 takes the pixels as HxWx4, so the size comes from
                # the array and these two leave the MATLAB signature.
                out.append(Param("IMG" + name.upper(), name, t))
            elif name in ENUM_PARAMS:
                out.append(Param("ENUM", name, t))
            elif name == "image":
                out.append(Param("IMAGE", name, t))
            elif name in ("font", "baseFont", "fallbackFont"):
                out.append(Param("FONT", name, t))
            elif name == "freeData":
                out.append(Param("FREEDATA", name, t))
            else:
                out.append(Param("I", name, t))
        elif t == "unsigned char":
            out.append(Param("UC", name, t))
        elif t == "const char *":
            if name == "end":
                raise Unsupported("unpaired string end pointer")
            if nxt_t == "const char *" and nxt_name == "end":
                out.append(Param("STR", name, t))
                out.append(Param("STREND", nxt_name, nxt_t))
                i += 2
                continue
            out.append(Param("STR", name, t))
        elif t in ("float *", "const float *"):
            if t.startswith("const"):
                out.append(Param("XFORM_IN", name, t))
            elif name == "bounds":
                out.append(Param("BOUNDS_OUT", name, t))
            elif name in ("dstx", "dsty", "ascender", "descender", "lineh"):
                out.append(Param("FOUT", name, t))
            elif name in ("dst", "xform"):
                kind = "XFORM_INOUT" if fn_name in XFORM_INOUT_FUNCS else "XFORM_OUT"
                out.append(Param(kind, name, t))
            else:
                raise Unsupported("unknown float* parameter %r" % name)
        elif t == "int *":
            out.append(Param("IOUT", name, t))
        elif t in ("unsigned char *", "const unsigned char *"):
            if fn_name in IMAGE_DATA_FUNCS:
                out.append(Param("IMGDATA", name, t))
            elif nxt_t in ("int", "const int") and nxt_name == "ndata":
                out.append(Param("DATA", name, t))
                out.append(Param("NDATA", nxt_name, nxt_t))
                i += 2
                continue
            else:
                raise Unsupported("unknown byte pointer %r" % name)
        elif t == "NVGglyphPosition *":
            if not (nxt_t in ("int", "const int") and nxt_name == "maxPositions"):
                raise Unsupported("glyph array without maxPositions")
            out.append(Param("GLYPHS_OUT", name, t))
            out.append(Param("MAXGLYPHS", nxt_name, nxt_t))
            i += 2
            continue
        elif t == "NVGtextRow *":
            if not (nxt_t in ("int", "const int") and nxt_name == "maxRows"):
                raise Unsupported("row array without maxRows")
            out.append(Param("ROWS_OUT", name, t))
            out.append(Param("MAXROWS", nxt_name, nxt_t))
            i += 2
            continue
        elif t == "void":
            pass
        else:
            raise Unsupported("unhandled parameter type %r" % t)
        i += 1
    return out


IN_KINDS = ("F", "I", "UC", "ENUM", "IMAGE", "FONT", "COLOR", "PAINT", "STR",
            "XFORM_IN", "XFORM_INOUT", "DATA", "IMGDATA")
OPTIONAL_KINDS = ("MAXROWS",)


class Binding(object):
    def __init__(self, cname, mname, ret, params, doc, group):
        self.cname = cname
        self.mname = mname
        self.ret = ret
        self.params = params
        self.doc = doc
        self.group = group

    @property
    def inputs(self):
        return [p for p in self.params if p.kind in IN_KINDS]

    @property
    def optional(self):
        return [p for p in self.params if p.kind in OPTIONAL_KINDS]

    @property
    def outputs(self):
        """List of (label, kind) for the MATLAB outputs, in order."""
        outs = []
        if self.ret == "float" or self.ret == "int":
            outs.append(("value", "RET_NUM"))
        elif self.ret == "NVGcolor":
            outs.append(("color", "RET_COLOR"))
        elif self.ret == "NVGpaint":
            outs.append(("paint", "RET_PAINT"))
        elif self.ret != "void":
            raise Unsupported("unhandled return type %r" % self.ret)
        scalars = [p for p in self.params if p.kind in ("FOUT", "IOUT")]
        names = tuple(p.name for p in scalars)
        if names in PAIR_OUTPUTS:
            outs.append((names[0] + names[1], "OUT_PAIR"))
        else:
            for p in scalars:
                outs.append((p.name, "OUT_SCALAR"))
        for p in self.params:
            if p.kind == "XFORM_OUT" or p.kind == "XFORM_INOUT":
                outs.insert(0, (p.name, "OUT_XFORM"))
            elif p.kind == "BOUNDS_OUT":
                outs.append((p.name, "OUT_BOUNDS"))
            elif p.kind == "GLYPHS_OUT":
                outs.append((p.name, "OUT_GLYPHS"))
            elif p.kind == "ROWS_OUT":
                outs.append((p.name, "OUT_ROWS"))
        return outs

    @property
    def needs_ctx(self):
        return any(p.kind == "CTX" for p in self.params)


# Frame-scoped groups. NanoVG resets its state stack inside nvgBeginFrame, so
# every call that reads or writes that state belongs to a frame.
GROUP_OF = {}


def group_for(cname):
    name = cname[3:]
    if name in ("Save", "Restore", "Reset"):
        return "State"
    if name in ("ShapeAntiAlias", "StrokeColor", "StrokePaint", "FillColor",
                "FillPaint", "MiterLimit", "StrokeWidth", "LineCap",
                "LineJoin", "GlobalAlpha", "GlobalCompositeOperation",
                "GlobalCompositeBlendFunc",
                "GlobalCompositeBlendFuncSeparate"):
        return "Render styles"
    if name in ("ResetTransform", "Transform", "Translate", "Rotate", "SkewX",
                "SkewY", "Scale", "CurrentTransform"):
        return "Transforms"
    if name.startswith("Transform") or name in ("DegToRad", "RadToDeg"):
        return "Transform helpers"
    if name.startswith("CreateImage") or name in ("UpdateImage", "ImageSize",
                                                  "DeleteImage"):
        return "Images"
    if name in ("LinearGradient", "BoxGradient", "RadialGradient",
                "ImagePattern"):
        return "Paints"
    if name in ("Scissor", "IntersectScissor", "ResetScissor"):
        return "Scissoring"
    if name in ("BeginPath", "MoveTo", "LineTo", "BezierTo", "QuadTo", "ArcTo",
                "ClosePath", "PathWinding", "Arc", "Rect", "RoundedRect",
                "RoundedRectVarying", "Ellipse", "Circle", "Fill", "Stroke"):
        return "Paths"
    if name in ("RGB", "RGBA", "RGBf", "RGBAf", "LerpRGBA", "TransRGBA",
                "TransRGBAf", "HSL", "HSLA"):
        return "Colors"
    if (name.startswith("Font") or name.startswith("Text")
            or name.startswith("CreateFont") or name.startswith("AddFallback")
            or name.startswith("ResetFallback") or name == "FindFont"):
        return "Text"
    return "Other"


