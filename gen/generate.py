def m_signature(b):
    ins = []
    for p in b.inputs:
        ins.append(p.name)
    for p in b.optional:
        ins.append("[" + p.name + "]")
    outs = [label for label, _k in b.outputs]
    call = "PsychNanoVG('%s'%s)" % (b.mname,
                                    "".join(", " + i for i in ins))
    if not outs:
        return call
    if len(outs) == 1:
        return "%s = %s" % (outs[0], call)
    return "[%s] = %s" % (", ".join(outs), call)


