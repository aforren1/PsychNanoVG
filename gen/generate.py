def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if not text.endswith("\n"):
        text += "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s" % os.path.relpath(path, ROOT))


def nanovg_commit():
    try:
        res = subprocess.run(["git", "-C",
                              os.path.join(ROOT, "third_party", "nanovg"),
                              "rev-parse", "HEAD"],
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                             check=True)
        return res.stdout.decode().strip()[:12]
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main():
    if not os.path.exists(NANOVG_H):
        sys.stderr.write(
            "nanovg.h not found at %s\n"
            "Clone it first: git clone https://github.com/memononen/nanovg.git"
            " third_party/nanovg\n" % NANOVG_H)
        return 2

    text = preprocess(NANOVG_H)
    ast = c_parser.CParser().parse(text, filename="nanovg.h")
    docs = collect_docs(NANOVG_H)
    excl, rename = read_allowlist(os.path.join(HERE, "allowlist.txt"))

    enums = collect_enums(ast)
    enums.update(collect_gl_enums(NANOVG_GL_H))

    bindings, dropped = [], []
    for node in ast.ext:
        if not isinstance(node, c_ast.Decl):
            continue
        if not isinstance(node.type, c_ast.FuncDecl):
            continue
        cname = node.name
        if not cname or not cname.startswith("nvg"):
            continue
        if cname in excl:
            dropped.append((cname, "excluded by allowlist.txt"))
            continue
        try:
            ret = type_name(node.type.type)
            params = node.type.args.params if node.type.args else []
            kinds = classify(cname, params)
            mname = rename.get(cname, cname[3:])
            b = Binding(cname, mname, ret, kinds, docs.get(cname, ""),
                        group_for(cname))
            b.outputs  # raises Unsupported on an unknown return type
            bindings.append(b)
        except (Unsupported, KeyError) as e:
            dropped.append((cname, str(e)))

    bindings.sort(key=lambda b: b.mname)
    version = "0.2.0+nanovg.%s" % nanovg_commit()

    cmds = emit_dispatch(bindings, os.path.join(ROOT, "src", "gen_dispatch.c"),
                         version)
    emit_enums(enums, os.path.join(ROOT, "src", "gen_enums.c"))
    emit_help_m(bindings, cmds, os.path.join(ROOT, "m", "PsychNanoVG.m"),
                version)
    emit_op_m(cmds, os.path.join(ROOT, "m", "PsychNanoVGOp.m"))
    emit_marshal_test(bindings,
                      os.path.join(ROOT, "tests", "test_gen_marshal.m"))

    print("%d generated subcommands, %d hand-written, %d commands total, "
          "%d enum constants" % (len(bindings), len(HANDWRITTEN), len(cmds),
                                 len(enums)))
    if dropped:
        print("dropped:")
        for name, why in dropped:
            print("  %-32s %s" % (name, why))
    return 0


if __name__ == "__main__":
    sys.exit(main())
