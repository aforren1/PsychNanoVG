def read_allowlist(path):
    excl, rename = set(), {}
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            s = line.strip()
            if not s or s.startswith("#") or s.startswith("!"):
                continue
            if s.startswith("-"):
                excl.add(s[1:].strip())
            elif s.startswith("="):
                parts = s[1:].split()
                if len(parts) == 2:
                    rename[parts[0]] = parts[1]
    return excl, rename


# ---------------------------------------------------------------------------
# Constant expression evaluation for enums
# ---------------------------------------------------------------------------


def eval_const(node, known):
    if node is None:
        return None
    if isinstance(node, c_ast.Constant):
        return int(node.value, 0)
    if isinstance(node, c_ast.ID):
        return known[node.name]
    if isinstance(node, c_ast.UnaryOp):
        v = eval_const(node.expr, known)
        return {"-": -v, "+": v, "~": ~v}[node.op]
    if isinstance(node, c_ast.BinaryOp):
        a = eval_const(node.left, known)
        b = eval_const(node.right, known)
        return {"<<": a << b, ">>": a >> b, "|": a | b, "&": a & b,
                "+": a + b, "-": a - b, "*": a * b}[node.op]
    raise ValueError("cannot evaluate enum value: %r" % node)


def collect_enums(ast):
    values = {}
    for node in ast.ext:
        for sub in walk_enums(node):
            nxt = 0
            for item in sub.values.enumerators:
                if item.value is not None:
                    nxt = eval_const(item.value, values)
                values[item.name] = nxt
                nxt += 1
    return values


def walk_enums(node):
    found = []

    class V(c_ast.NodeVisitor):
        def visit_Enum(self, n):
            if n.values is not None:
                found.append(n)
            self.generic_visit(n)

    V().visit(node)
    return found


def collect_gl_enums(path):
    """Pull `enum NVGcreateFlags` out of nanovg_gl.h.

    The GL header cannot be preprocessed without GL headers, and the block is
    a plain list of shift constants, so read it textually.
    """
    with open(path, "r", encoding="utf-8") as fh:
        text = strip_comments(fh.read())
    m = re.search(r"enum\s+NVGcreateFlags\s*\{(.*?)\}", text, flags=re.S)
    if not m:
        return {}
    out, nxt = {}, 0
    for part in m.group(1).split(","):
        part = part.strip()
        if not part:
            continue
        if "=" in part:
            name, expr = part.split("=", 1)
            nxt = eval_shift(expr.strip())
            name = name.strip()
        else:
            name = part
        out[name] = nxt
        nxt += 1
    return out


def eval_shift(expr):
    m = re.fullmatch(r"(\d+)\s*<<\s*(\d+)", expr)
    if m:
        return int(m.group(1)) << int(m.group(2))
    return int(expr, 0)


