def collect_docs(path):
    """Map nvg function name to the `//` block above its declaration."""
    with open(path, "r", encoding="utf-8") as fh:
        lines = fh.read().splitlines()
    docs = {}
    block = []
    for line in lines:
        s = line.strip()
        if s.startswith("//"):
            block.append(s[2:].strip())
            continue
        m = re.search(r"\b(nvg[A-Za-z0-9]+)\s*\(", s)
        if m and block:
            docs.setdefault(m.group(1), " ".join(x for x in block if x))
        if s:
            block = []
    return docs


