def m_literal_for(p):
    k = p.kind
    if k == "F":
        return "1"
    if k == "UC":
        return "128"
    if k == "ENUM":
        return str(ENUM_TEST_VALUE.get(p.name, 0))
    if k == "IMAGE":
        return "img"
    if k == "FONT":
        return "fnt"
    if k == "I":
        if p.name == "fontIndex":
            return "0"
        return "1"
    if k == "COLOR":
        return "[1 0.5 0.25 1]"
    if k == "PAINT":
        return "pnt"
    if k == "STR":
        if p.name in ("string", "name", "font", "baseFont", "fallbackFont"):
            return "'abc'"
        return "'abc'"
    if k in ("XFORM_IN", "XFORM_INOUT"):
        return "[1 0 0 1 0 0]"
    if k == "DATA":
        return "uint8(1:32)"
    if k == "IMGDATA":
        return "zeros(8, 8, 4, 'uint8')"
    if k == "MAXROWS":
        return "8"
    return "1"


