def find_preprocessor():
    """Return an argv prefix that preprocesses a C file to stdout.

    MSVC needs a full environment to run, so a plain gcc is preferred. Octave
    ships one on Windows. Returning None makes the caller fall back to the
    built-in stripper, which is enough for nanovg.h because the header has no
    includes and no function-like macros in its declarations.
    """
    candidates = ["cc", "gcc", "clang"]
    octave_gcc = r"C:\Program Files\GNU Octave\Octave-10.1.0\mingw64\bin\gcc.exe"
    if os.path.exists(octave_gcc):
        candidates.append(octave_gcc)
    for cc in candidates:
        try:
            subprocess.run([cc, "--version"], stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, check=True)
        except (OSError, subprocess.CalledProcessError):
            continue
        return [cc, "-E", "-std=c99", "-P"]
    return None


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def builtin_preprocess(text):
    """Minimal preprocessor for nanovg.h.

    Handles only what the header uses: comments, `#ifndef` include guards,
    `#ifdef __cplusplus`, and `#pragma`. No macro expansion is needed because
    every declaration in nanovg.h is plain C.
    """
    text = strip_comments(text)
    out = []
    # A stack of "is this branch live" flags.
    live = [True]
    defined = {"NANOVG_H": False}
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("#"):
            d = s[1:].strip()
            word = d.split()[0] if d else ""
            if word in ("ifdef", "ifndef", "if"):
                if word == "ifdef":
                    cond = defined.get(d.split()[1], False)
                elif word == "ifndef":
                    cond = not defined.get(d.split()[1], False)
                else:
                    cond = False  # nanovg.h has no plain #if that matters
                live.append(live[-1] and cond)
            elif word == "else":
                top = live.pop()
                live.append(live[-1] and not top)
            elif word == "endif":
                if len(live) > 1:
                    live.pop()
            elif word == "define" and live[-1]:
                parts = d.split()
                if len(parts) >= 2:
                    defined[parts[1]] = True
            continue
        if live[-1]:
            out.append(line)
    return "\n".join(out)


def preprocess(path):
    with open(path, "r", encoding="utf-8") as fh:
        raw = fh.read()
    cpp = find_preprocessor()
    if cpp:
        with tempfile.TemporaryDirectory() as td:
            tmp = os.path.join(td, "nanovg_in.h")
            with open(tmp, "w", encoding="utf-8") as fh:
                fh.write(raw)
            try:
                res = subprocess.run(cpp + [tmp], stdout=subprocess.PIPE,
                                     stderr=subprocess.PIPE, check=True)
                text = res.stdout.decode("utf-8", "replace")
            except (OSError, subprocess.CalledProcessError):
                text = builtin_preprocess(raw)
    else:
        text = builtin_preprocess(raw)
    # pycparser rejects linemarkers and pragmas.
    keep = [ln for ln in text.splitlines()
            if not ln.lstrip().startswith("#")]
    return "\n".join(keep)


